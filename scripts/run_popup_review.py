def _read_resource(path: Path) -> str:
    """Read a bundled prompt/reference as immutable UTF-8 model context."""
    _reject_symlink(path, "prompt resource")
    _require_regular_readable(path, "prompt resource")
    text = path.read_text(encoding="utf-8")
    if not text.strip():
        raise ValueError(f"prompt resource is empty: {path}")
    return text


def _render_resource(path: Path, **values: object) -> str:
    text = _read_resource(path)
    for key, value in values.items():
        text = text.replace("{{" + key + "}}", str(value))
    if "{{" in text or "}}" in text:
        raise ValueError(f"prompt resource has unresolved template variables: {path}")
    return text


@dataclass(frozen=True)
class PopupManifest:
    """The deterministic popup ID correspondence generated by preparation."""

    path: Path | None
    blocks: tuple[Mapping[str, Any], ...]
    schema_version: int = 1

    @property
    def ids(self) -> tuple[str, ...]:
        return tuple(str(block["id"]) for block in self.blocks)

    @classmethod
    def from_path(cls, path: Path) -> "PopupManifest":
        _require_regular_readable(path, "popup manifest")
        payload = json.loads(path.read_text(encoding="utf-8"))
        return cls.from_payload(payload, path=path.resolve())

    @classmethod
    def from_payload(
        cls,
        payload: Mapping[str, Any],
        *,
        path: Path | None = None,
    ) -> "PopupManifest":
        if not isinstance(payload, Mapping):
            raise ValueError("popup manifest must be an object")
        version = payload.get("schema_version", 1)
        if version != 1:
            raise ValueError(f"unsupported popup manifest schema_version: {version!r}")
        blocks = payload.get("blocks")
        popup_ids = payload.get("popup_ids")
        if not isinstance(blocks, list) or not isinstance(popup_ids, list):
            raise ValueError("popup manifest requires blocks and popup_ids arrays")
        normalized: list[Mapping[str, Any]] = []
        required_fields = {
            "id",
            "order",
            "change_type",
            "label",
            "kind",
            "placeholder",
            "source_position",
            "relocated",
            "source_text",
        }
        for index, block in enumerate(blocks, 1):
            if not isinstance(block, Mapping):
                raise ValueError("popup manifest blocks must be objects")
            missing = sorted(required_fields.difference(block))
            if missing:
                raise ValueError(f"popup manifest block is missing required fields: {', '.join(missing)}")
            if block.get("order") != index:
                raise ValueError("popup manifest block order must be contiguous")
            block_id = block.get("id")
            if not isinstance(block_id, str) or not block_id:
                raise ValueError("popup manifest block IDs must be non-empty strings")
            change_type = block.get("change_type")
            kind = block.get("kind")
            if change_type not in {"delete", "add"}:
                raise ValueError(f"invalid popup change_type for {block_id}")
            if kind not in {"del", "add"} or (kind == "del") != (change_type == "delete"):
                raise ValueError(f"popup kind does not match change_type for {block_id}")
            if block.get("label") != change_type:
                raise ValueError(f"popup label does not match change_type for {block_id}")
            expected_placeholder = f"__COMMENT_{block_id.replace('-', '_')}__"
            if block.get("placeholder") != expected_placeholder:
                raise ValueError(f"popup placeholder does not match ID for {block_id}")
            position = block.get("source_position")
            if not isinstance(position, Mapping):
                raise ValueError(f"source_position is required for {block_id}")
            for coordinate in ("line", "column"):
                value = position.get(coordinate)
                if isinstance(value, bool) or not isinstance(value, int) or value < 1:
                    raise ValueError(f"source_position.{coordinate} must be a positive integer for {block_id}")
            if not isinstance(block.get("relocated"), bool):
                raise ValueError(f"popup relocated must be boolean for {block_id}")
            if not isinstance(block.get("source_text"), str):
                raise ValueError(f"popup source_text must be a string for {block_id}")
            normalized.append(dict(block))
        if any(not isinstance(value, str) or not value for value in popup_ids):
            raise ValueError("popup_ids must contain non-empty strings")
        ids = tuple(popup_ids)
        if ids != tuple(block["id"] for block in normalized):
            raise ValueError("popup_ids must match blocks in order")
        if len(set(ids)) != len(ids):
            raise ValueError("popup manifest contains duplicate IDs")
        resolved_path = None if path is None else Path(path).resolve()
        return cls(path=resolved_path, blocks=tuple(normalized), schema_version=1)

    @classmethod
    def from_blocks(
        cls,
        blocks: Sequence[DiffBlock],
        *,
        path: Path | None = None,
    ) -> "PopupManifest":
        return cls.from_payload(popup_manifest_payload(list(blocks)), path=path)


